"""newsdigest — дайджест новостей в Telegram на одной стандартной библиотеке.

Пакет собран так, чтобы каждый модуль отвечал за один слой и его можно было
читать и править отдельно:

    config     настройки, окружение, часовой пояс, логирование
    profiles   темы: встроенные + пользовательские (~/.newsdigest/profiles.json)
    net        HTTP: один opener, ретраи, gzip, 308-редиректы
    feedparse  разбор RSS/Atom
    textutil   канонизация ссылок, сигнатуры, похожесть
    storage    SQLite: схема, миграции, подписчики, реакции, закладки
    sources    сбор материалов из фидов и Hacker News
    rank       кластеризация, прескоринг, отбор в выпуск
    llm        обращения к модели: ранжирование и карточки
    telegram   транспорт Telegram Bot API
    render     сборка текста выпуска
    pipeline   конвейер «собрать → отранжировать → отправить»
    bot        разбор входящих команд и нажатий кнопок
    daemon     фоновый цикл: расписание + приём апдейтов
    cli        разбор аргументов командной строки
"""

